"""Explainer page per substantial unit (Geoffrey Litt's "understanding is the new bottleneck"):
background, intuition with toy data and diagrams, a code walkthrough in conceptual order, and a 5-question quiz,
as one self-contained HTML file saved outside the repo. Generated by Codex (its config's default model), read-only.

  tokenmaxxing explain [--repo D] [--commit SHA | --base REF] [--slug S] [--focus T] [--background] [--effort E]

Output: <explain.dir, default ~/Documents/explainers>/YYYY-MM-DD-<slug>.html
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from gutcheck_core import config, secretscan

from . import jobs, relevance

PROMPT = Path(__file__).with_name("prompts") / "explain-diff.md"
MAX_DIFF_CHARS = 120_000


def out_dir():
    d = config.load().get("explain", {}).get("dir") or str(Path.home() / "Documents" / "explainers")
    return Path(os.path.expanduser(d))


def build_prompt(repo, commit=None, base=None, focus=None):
    rel, rel_path = relevance.build(repo, commit, base, focus)
    label, diff = relevance.get_diff(relevance.repo_root(repo), commit, base)
    diff = secretscan.redact(diff)
    if len(diff) > MAX_DIFF_CHARS:
        diff = diff[:MAX_DIFF_CHARS] + f"\n... (diff truncated at {MAX_DIFF_CHARS} chars; read the rest with git)"
    root = rel["repo"]
    note = ""
    if commit:
        subj = relevance.git(root, "log", "-1", "--format=%s%n%n%b", commit).strip()
        note = (f"- Commit message:\n\n{subj[:2000]}\n\n- The working tree may have moved on since this commit: read "
                f"files as they were with `git show {commit}:<path>`.")
    if focus:
        note += f"\n- What the orchestrator wants the reader to understand: {focus}"
    text = PROMPT.read_text()
    for k, v in {"repo": root, "scope": label, "commit_note": note,
                 "relevance": relevance.render_md(rel), "diff": diff}.items():
        text = text.replace("{" + k + "}", v)
    return text, rel, label


def extract_html(text):
    m = re.search(r"<!DOCTYPE html.*?</html>", text, re.S | re.I) or re.search(r"<html.*?</html>", text, re.S | re.I)
    return m.group(0) if m else None


def check_html(html):
    """Deterministic checks from the skill: sections, interactive quiz, code blocks keep newlines, offline."""
    low = html.lower()
    probs = []
    if len(re.findall(r"<h2[\s>]", low)) < 4:
        probs.append("fewer than 4 top-level sections")
    if "<script" not in low:
        probs.append("no script (quiz not interactive)")
    if "quiz" not in low and "check your" not in low and "question" not in low:
        probs.append("no quiz found")
    if re.search(r"<(script|link|img|iframe)[^>]+(src|href)=[\"']?https?://", low) or "@import url(http" in low:
        probs.append("loads a network resource")
    buttons = re.findall(r"<button\b[^>]*>", low)
    for attr in {a for b in buttons for a in re.findall(r"\b(data-[\w-]+)=", b)}:
        have = sum(attr in b for b in buttons)
        if 0 < have < len(buttons) and have >= len(buttons) // 2:
            probs.append(f"{len(buttons) - have} of {len(buttons)} buttons lack {attr} (quiz grading may break)")
    for name, body in re.findall(r"\.([\w-]*code[\w-]*)\s*\{([^}]*)\}", low):
        if re.search(rf"<div[^>]+class=\"[^\"]*\b{re.escape(name)}\b", low) and "white-space" not in body:
            probs.append(f"code block class .{name} lacks white-space: pre-wrap")
    return probs


def run(repo=".", commit=None, base=None, slug=None, focus=None, effort=None, job_dir=None):
    prompt, rel, label = build_prompt(repo, commit, base, focus)
    codex = shutil.which("codex")
    if not codex:
        raise SystemExit("tokenmaxxing explain: codex CLI not found on PATH")
    if not slug:
        subj = relevance.git(rel["repo"], "log", "-1", "--format=%s", commit).strip() if commit else (focus or "")
        slug = jobs.slug(f"{Path(rel['repo']).name} {subj}")
    dest = out_dir() / f"{time.strftime('%Y-%m-%d')}-{jobs.slug(slug, 60)}.html"
    work = Path(job_dir) if job_dir else jobs.new("explain", slug)[1]
    (work / "prompt.md").write_text(prompt)
    last = work / "last-message.txt"
    cmd = [codex, "exec", "-C", rel["repo"], "--sandbox", "read-only", "--skip-git-repo-check",
           "--color", "never", "-o", str(last), "-"]
    if effort:
        cmd[2:2] = ["-c", f"model_reasoning_effort={effort}"]
    jobs.write_status(work, kind="explain", dest=str(dest), repo=rel["repo"], scope=label, state="running")
    t0 = time.time()
    with open(work / "codex.log", "wb") as log:
        r = subprocess.run(cmd, input=prompt.encode(), stdout=log, stderr=subprocess.STDOUT)
    secs = round(time.time() - t0)
    html = extract_html(last.read_text(errors="replace")) if last.exists() else None
    if not html:
        jobs.write_status(work, state="failed", exit=r.returncode, seconds=secs,
                          error="no HTML document in Codex's final message; see codex.log")
        return None, work
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(html)
    problems = check_html(html)
    jobs.write_status(work, state="done", exit=r.returncode, seconds=secs, bytes=len(html), problems=problems)
    with open(config.STATE_DIR / "explain.jsonl", "a") as fh:
        fh.write(json.dumps({"t": time.strftime("%Y-%m-%dT%H:%M:%S"), "repo": Path(rel["repo"]).name, "scope": label,
                             "dest": str(dest), "seconds": secs, "bytes": len(html), "problems": problems}) + "\n")
    return dest, work


def main(args):
    from gutcheck_core.args import _flag, _opt
    repo = _opt(args, "--repo", ".")
    commit, base = _opt(args, "--commit"), _opt(args, "--base")
    slug, focus, effort = _opt(args, "--slug"), _opt(args, "--focus"), _opt(args, "--effort")
    job_dir = _opt(args, "--job-dir")
    if _flag(args, "--background"):
        root = str(relevance.repo_root(repo))
        jid, d = jobs.new("explain", slug or focus or commit or Path(root).name)
        argv = ["explain", "--repo", root, "--job-dir", str(d)]
        for k, v in (("--commit", commit), ("--base", base), ("--slug", slug), ("--focus", focus), ("--effort", effort)):
            if v:
                argv += [k, v]
        jobs.spawn(d, argv)
        print(f"tokenmaxxing explain: started in the background ({jid}). The page lands in {out_dir()}/ "
              f"(exact path in {d}/status.json when done).")
        return
    dest, work = run(repo, commit, base, slug, focus, effort, job_dir)
    if dest:
        st = jobs.read_status(work)
        print(f"{dest}" + (f"  (checks: {'; '.join(st.get('problems') or [])})" if st.get("problems") else ""))
    else:
        sys.exit(f"tokenmaxxing explain: failed; see {work}/codex.log")
